package emit

import (
	"strings"
	"testing"
)

var linkSchema = map[string]any{
	"title":       "Link",
	"description": "A typed link.",
	"type":        "object",
	"required":    []any{"type", "url"},
	"properties": map[string]any{
		"type":  map[string]any{"type": "string", "description": "Link relation type."},
		"url":   map[string]any{"type": "string", "maxLength": float64(2048)},
		"title": map[string]any{"type": "string", "pattern": "^[^\\n]*$"},
	},
}

func TestEmitStruct(t *testing.T) {
	src, err := EmitFile("shopping", "test/link.json", linkSchema, "release/test@deadbeef")
	if err != nil {
		t.Fatalf("EmitFile: %v", err)
	}
	for _, want := range []string{
		"// Code generated by ucpgen. DO NOT EDIT.",
		"package shopping",
		"type Link struct {",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("emitted source missing %q\n---\n%s", want, src)
		}
	}
	// gofmt column-aligns struct fields (extra spaces between name/type/tag
	// to line up with sibling fields), so field assertions collapse
	// whitespace runs before comparing.
	collapsed := collapse(src)
	for _, want := range []string{
		"Type string `json:\"type\"`",
		"URL string `json:\"url\"`",
		"Title *string `json:\"title,omitempty\"`",
	} {
		if !strings.Contains(collapsed, want) {
			t.Errorf("emitted source missing %q\n---\n%s", want, src)
		}
	}
}

func collapse(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func TestGoName(t *testing.T) {
	for in, want := range map[string]string{
		"url": "URL", "line_item": "LineItem", "ap2_mandate": "AP2Mandate",
		"id": "ID", "payment_handler": "PaymentHandler",
		"dev.ucp.buyer_ip": "DevUCPBuyerIP",
		"2fa_code":         "V2faCode",
	} {
		if got := GoName(in); got != want {
			t.Errorf("GoName(%q) = %q, want %q", in, got, want)
		}
	}
}
